DEFAULT_FIELDS_JA = [
    "伝票番号",
    "伝票日付",
    "出庫日付",
    "製品コード",
    "単位",
    "数量",
    "入庫倉庫",
    "住所",
    "ARコード",
]

METADATA_FIELDS_JA = [
    "伝票番号",
    "入庫倉庫",
    "住所",
    "ARコード",
    "伝票日付",
    "出庫日付",
]

TABLE_ROW_FIELDS_JA = [f for f in DEFAULT_FIELDS_JA if f not in METADATA_FIELDS_JA]


def get_extraction_prompt_ja() -> str:
    """日本語フィールド名で日本語抽出プロンプトを生成"""
    
    prompt = f"""このベトナム語の出庫伝票から構造化データを抽出し、JSON形式で返してください。

出力要件:
- 以下の構造でJSON形式でデータを返す:
{{
  "metadata": {{
    {", ".join([f'"{f}": <値またはnull>' for f in METADATA_FIELDS_JA])}
  }},
  "table_rows": [
    {{
      {", ".join([f'"{f}": <値またはnull>' for f in TABLE_ROW_FIELDS_JA])}
    }}
  ]
}}

#抽出手順:

### メタデータフィールド:

1. 伝票番号
   - メインの伝票/PO番号、通常は右上のヘッダーエリアにあります
   - 一般的な形式: "PXB25110076", "2544051804257", "252.104.868.0263"
   - ドット、ダッシュ、スペースを含めて表示通りに正確に抽出
   - 手書きのページ番号("1/2"など)や顧客コードの後の番号ではありません

2. 伝票日付(dd/mm/yyyy)
   - 伝票発行日をdd/mm/yyyy形式で
   - 伝票に表示されている通りに正確に抽出
   - 複数の日付がある場合は、発行日/伝票日とラベル付けされているものを選択

3. 出庫日付(dd/mm/yyyy)
   - 配送または出荷日をdd/mm/yyyy形式で
   - 伝票に表示されている通りに正確に抽出
   - 伝票日付と同じ場合も異なる場合もあります

4. 入庫倉庫
   - 商品を受け取る倉庫または顧客の名前
   - 例: "DC KHO HẢI PHÒNG", "Kho Hà Nội"
   - 表示されている通りにフルネームを抽出

5. 住所
   - 完全な配送先住所
   - オプションフィールド - 伝票に記載がない場合はnullに設定
   - 推測や推論はしない

6. ARコード
   - 顧客アカウントコード
   - 例: "A68/750", "A68/750_141", "AR1830"
   - アンダースコアの後の接尾辞を含む完全なコードを抽出

### テーブルフィールド:

7. 製品コード
   - 製品識別子、通常はテーブルの最も左の列
   - 例: "PG1490", "FC9345", "PL2368"
   - 正確な英数字コードを抽出

8. 単位
   - 製品の測定単位
   - 例: "Hộp"(箱), "Gói"(パック), "Chai"(ボトル), "Thùng"(カートン)
   - テキストをそのまま保持

9. 数量
   - 数値の数量値
   - 重要: 文字列型ではなく数値型である必要があります
   - 例: {{"数量": 168}} であって {{"数量": "168"}} ではありません

重要なルール:
- マークダウン形式や説明なしで有効なJSONのみを返す
- 数量フィールドは数値型(整数または浮動小数点数)である必要があります。他のすべてのフィールドは文字列またはnull
- 日付はすでにdd/mm/yyyy形式 - 表示通りに正確に抽出
- テーブル内の各製品行がtable_rows配列内の1つのオブジェクトを作成
- テキスト値内のベトナム語の発音記号を保持(ă, â, đ, ê, ô, ơ, ư など)
- 見つからない場合はフィールドをnullに設定 - 推測や仮定をしない
- 伝票番号はヘッダーにあります。顧客コードの後に表示される番号ではありません
- 存在する場合は接尾辞を含む完全なARコードを含める
"""
    
    return prompt